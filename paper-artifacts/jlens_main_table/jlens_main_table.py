"""The main-body J-lens table (artifacts/jlens_main_table_2block.tex in the paper repo): the top-5 tokens at
each pole of the four deployed directions, in two blocks. Block 1 is the pole each intervention pushes toward
(-u for the cap, +v_spec for the floor, +v for the optimized addition, -v for the optimized cap), block 2 the
opposite pole. Reads jlens_main_readouts.json (jlens_main_readouts.py) and writes jlens_main_table_2block.tex
beside this script. Escaping, glosses and the equal-width column machinery follow jlens_pole_table.py.

    uv run python paper-artifacts/jlens_main_table/jlens_main_table.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "jlens_main_table_2block.tex"
K = 5
COLS = [   # header, block-1 pole, block-2 pole
    ("$u$", "-u", "+u"),
    (r"spec $v_{\mathrm{spec}}$", "+spec", "-spec"),
    ("opt add", "+opt_add", "-opt_add"),
    ("opt cap", "-opt_cap", "+opt_cap"),
]
POLE_LABEL = {"+u": "$+u$", "-u": "$-u$", "+spec": r"$+v_{\mathrm{spec}}$", "-spec": r"$-v_{\mathrm{spec}}$",
              "+opt_add": "$+v$", "-opt_add": "$-v$", "+opt_cap": "$+v$", "-opt_cap": "$-v$"}

GLOSS = {   # keyed on the stripped token; natural language that is not English. $^*$ = word fragment.
    "确认": "confirm", "证实": "corroborate", "正确": "correct", "继续": "continue", "拒绝": "refuse",
    "认可": "approve", "清理": "clean up", "优秀": "excellent", "优良": "high quality",
    "性价": r"$^*$value for money", "影幽": "shadow, dim", "iepazīšanās": "getting acquainted", "胞": r"$^*$cell",
    "装饰": "decorate", "подтвер": r"$^*$confirm",
}
ESC = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "_": r"\_", "&": r"\&", "%": r"\%",
       "#": r"\#", "$": r"\$", "^": r"\^{}", "~": r"\textasciitilde{}", "|": r"\textbar{}",
       "<": r"\textless{}", ">": r"\textgreater{}", "`": r"\textasciigrave{}", "-": "-{}"}
esc = lambda s: "".join(ESC.get(c, c) for c in s)
CJK = lambda s: any(0x2E80 <= ord(c) <= 0x9FFF or 0xF900 <= ord(c) <= 0xFAFF or 0x3000 <= ord(c) <= 0x303F for c in s)
CYR = lambda s: any(0x400 <= ord(c) <= 0x4FF for c in s)


def strip(t):
    """Token without its leading/trailing whitespace; an all-whitespace token keeps its newlines."""
    return t.strip() or t.replace(" ", "")


def tok(t):
    t = t.replace("\n", "\\n").replace("\t", "\\t")
    if CJK(t):
        parts, run = [], ""
        for c in t:
            if CJK(c): run += c
            else:
                if run: parts.append(("cjk", run)); run = ""
                parts.append(("ascii", c))
        if run: parts.append(("cjk", run))
        return "".join(rf"\cjk{{{p}}}" if kind == "cjk" else esc(p) for kind, p in parts)
    if CYR(t):
        return rf"\cyr{{{t}}}"
    return rf"\texttt{{{esc(t)}}}"


def cell(t):
    s = strip(t); g = GLOSS.get(s, "")
    return tok(s) + (rf" {{\tiny\textit{{({g})}}}}" if g else "")


R = json.loads((HERE / "jlens_main_readouts.json").read_text())["readouts"]
blocks = []   # [(pole labels, rows of cells)] for the two blocks
for b in (1, 2):
    poles = [c[b] for c in COLS]
    rows = [[cell(R[p][i][0]) for p in poles] for i in range(K)]
    blocks.append(([POLE_LABEL[p] for p in poles], rows))

# Equal column widths: every cell measured in the table's own size; all four columns take the widest,
# capped so the table fits the line (see jlens_pole_table.py).
heads = [c[0] for c in COLS]
L = [r"% Generated by paper-artifacts/jlens_main_table/jlens_main_table.py (two-block variant) -- do not edit by hand.",
     r"\setlength{\tabcolsep}{2pt}\renewcommand{\arraystretch}{1.05}\scriptsize",
     r"\newlength{\jlbcol}\newlength{\jlbcell}\setlength{\jlbcol}{0pt}"]
for c in heads + [rows[i][j] for j in range(len(COLS)) for _, rows in blocks for i in range(K)]:   # column-major across both blocks
    L.append(rf"\settowidth{{\jlbcell}}{{{c}}}\ifdim\jlbcell>\jlbcol\setlength{{\jlbcol}}{{\jlbcell}}\fi")
GAP = "6pt"
L += [r"\settowidth{\jlbcell}{%d}\addtolength{\jlbcell}{%d\tabcolsep}\addtolength{\jlbcell}{%s}" % (K, 2 * len(COLS), GAP),
      r"\setlength{\jlbcell}{\dimexpr(\linewidth-\jlbcell)/%d\relax}" % len(COLS),
      r"\ifdim\jlbcol>\jlbcell\setlength{\jlbcol}{\jlbcell}\fi",
      r"\begin{tabular}{@{}l<{\hspace{%s}}*{%d}{>{\raggedright\arraybackslash}p{\jlbcol}}@{}}" % (GAP, len(COLS)),
      r"\toprule", " & ".join([""] + heads) + r" \\", r"\midrule"]
for i, (labels, rows) in enumerate(blocks):
    if i: L.append(r"\midrule")
    L.append(r"\multicolumn{1}{@{}l}{} & " + " & ".join(rf"\textit{{{l}}}" for l in labels) + r" \\[1pt]")
    L += [" & ".join([str(r_i + 1)] + [rf"\mbox{{{c}}}" for c in cells]) + r" \\" for r_i, cells in enumerate(rows)]
L += [r"\bottomrule", r"\end{tabular}"]
OUT.write_text("\n".join(L) + "\n")
print(OUT)
