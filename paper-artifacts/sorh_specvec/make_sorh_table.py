"""The paper's School of Reward Hacks table (natural language = the 309 held-out writing prompts of Matthew's eval500):
every GLM-5-judged arm of record from sorh_all_arms.csv (sorh_data.py): hack, honest-and-complete (neither hacked nor
degenerate) and degenerate rates with 90% Wilson intervals, the counterpart of the coding table's hack / honest submit /
solve. Counts, p-values and the GPT-5.5-judged rows stay in the CSV. Writes sorh_summary_table.tex beside this script.
    uv run python paper-artifacts/sorh_specvec/make_sorh_table.py
"""
import math, os
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
d = pd.read_csv(os.path.join(HERE, "sorh_all_arms.csv")).fillna("")


def wilson(k, n, z=1.6448536):
    p = k / n; den = 1 + z * z / n; c = (p + z * z / (2 * n)) / den; h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return max(c - h, 0), c + h


def row(r):
    cells = [r.label]
    for k in (r.hack, r.hc, r.degen):
        lo, hi = wilson(k, r.n); cells += [f"{k / r.n:.2f}", f"{lo:.2f}--{hi:.2f}"]
    return " & ".join(cells) + r" \\"


L = [r"% Generated by paper-artifacts/sorh_specvec/make_sorh_table.py from sorh_all_arms.csv (sorh_data.py), 2026-09-26.",
     r"% 309 held-out natural-language School of Reward Hacks prompts, GLM-5 judge, n = 309 per row; doses selected on the",
     r"% 100-prompt dev set by the rule of record. opt = v3c (honest-submit completions), opt_ref = v3b (refusal-only).",
     r"% Rate and 90% Wilson CI for hack, honest and complete (neither hacked nor degenerate) and degenerate (Austin,",
     r"% 2026-10-09); counts, p-values and the GPT-5.5-judged u cap row are in sorh_all_arms.csv.",
     r"\begin{tabular}{l rr rr rr}", r"\toprule",
     r" & \multicolumn{2}{c}{hack} & \multicolumn{2}{c}{honest and complete} & \multicolumn{2}{c}{degenerate} \\",
     r"\cmidrule(lr){2-3} \cmidrule(lr){4-5} \cmidrule(lr){6-7}",
     r"arm & rate & 90\% CI & rate & 90\% CI & rate & 90\% CI \\", r"\midrule"]
g = d[d.judge == "GLM-5"]
for fam in ("baseline", "opt cap", "opt add", "spec floor", "spec add", "u add"):
    for r in g[g.family == fam].itertuples():
        L.append(row(r))
    L.append(r"\midrule")
L[-1] = r"\bottomrule"; L.append(r"\end{tabular}")
out = os.path.join(HERE, "sorh_summary_table.tex"); open(out, "w").write("\n".join(L) + "\n"); print("\n".join(L))
