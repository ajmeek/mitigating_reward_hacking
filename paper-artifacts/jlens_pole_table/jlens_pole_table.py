#!/usr/bin/env python3
"""Appendix table: top 10 J-lens tokens at L35 for +u, -u, +u_perp_e, -u_perp_e, +e and +s.

    uv run python paper-artifacts/jlens_pole_table/jlens_pole_table.py

Reads experiments/hack-action-anchor/artifacts/jlens_u_perp_e_L35.md (the u, u_perp_e and e poles)
and experiments/anti-hack-labeling/artifacts/jlens_s_L35.json (+s). Writes jlens_pole_table.tex
beside this script: one compact tabular, ranks down the rows and the six poles across the
columns, each cell "token (gloss)". Glosses are hand
translations of natural-language tokens that are not English; punctuation, whitespace, special
tokens and code get no gloss. Leading and trailing whitespace is stripped from every token (a token
that is nothing but whitespace keeps its \\n glyphs, or it would print as an empty cell). CJK needs
\\cjk and Cyrillic needs \\cyr (sections/commands.tex).
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).with_suffix(".tex")
K = 10
FENCE = "\x01"   # the source wraps each token in single backticks, so a token that is itself
                 # backticks cannot be parsed by that rule: swap it out before the regex

GLOSS = {            # keyed on the stripped token; natural language only, punctuation stays bare
    "确认": "confirm", "证实": "corroborate", "正确": "correct", "继续": "continue",
    "认可": "approve", "清理": "clean up", "优秀": "excellent", "优良": "high quality",
    "遗憾": "regrettable", "是正确的": "is correct", "没有问题": "no problem",
    "подтвер": r"$^*$confirm",   # $^*$ marks a word fragment (see the table caption)
}

CJK = lambda s: any(0x2E80 <= ord(c) <= 0x9FFF or 0xF900 <= ord(c) <= 0xFAFF for c in s)
CYR = lambda s: any(0x400 <= ord(c) <= 0x4FF for c in s)


def poles(path):
    out = {}
    src = Path(path).read_text().replace("` ``` ", f"`{FENCE}` ")
    for m in re.finditer(r"^## J-lens (\S+)\s*(\(([^)]*)\))?\s*\n\n(.+?)(?=\n##|\Z)", src, re.S | re.M):
        out[m.group(1)] = [(t, float(s)) for t, s in re.findall(r"`([^`]*)`\s*([0-9.]+)", m.group(4))]
    return out


ESC = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "_": r"\_", "&": r"\&", "%": r"\%",
       "#": r"\#", "$": r"\$", "^": r"\^{}", "~": r"\textasciitilde{}", "|": r"\textbar{}",
       "<": r"\textless{}", ">": r"\textgreater{}"}
esc = lambda s: "".join(ESC.get(c, c) for c in s)   # one pass, so a replacement's own braces are left alone


def strip(t):
    """Token without its leading/trailing whitespace; an all-whitespace token keeps its newlines."""
    if t == FENCE: return t
    return t.strip() or t.replace(" ", "")


def tok(t):
    """One stripped token as verbatim-ish LaTeX, with the wrapper its script needs."""
    if t == FENCE:
        return r"\texttt{\textasciigrave\textasciigrave\textasciigrave}"
    t = t.replace("⏎", "\\n").replace("\n", "\\n").replace("\t", "\\t")   # the md files use the glyph, the json real newlines
    body = esc(t)
    if CJK(t):
        # split so only the CJK run goes through \cjk (the wrapper switches font encoding)
        parts, run = [], ""
        for c in t:
            if CJK(c): run += c
            else:
                if run: parts.append(("cjk", run)); run = ""
                parts.append(("ascii", c))
        if run: parts.append(("cjk", run))
        return "".join(rf"\cjk{{{p}}}" if kind == "cjk" else esc(p) for kind, p in parts)
    if CYR(t):
        return rf"\cyr{{{t}}}"
    return rf"\texttt{{{body}}}"


B = poles(ROOT / "experiments/hack-action-anchor/artifacts/jlens_u_perp_e_L35.md")
S = json.load(open(ROOT / "experiments/anti-hack-labeling/artifacts/jlens_s_L35.json"))
B["+s"] = [(t, float(v)) for t, v in S["readouts"]["J-lens|+v"][:K]]
BLOCKS = [("$+u$", "+u"), ("$-u$", "-u"), (r"$+u_{\perp e}$", "+u_perp_e"),
          (r"$-u_{\perp e}$", "-u_perp_e"), ("$+e$", "+e"), ("$+s$", "+s")]

rows = []
for r_i in range(K):
    cells = []
    for _, key in BLOCKS:
        s = strip(B[key][r_i][0]); g = GLOSS.get(s, "")
        cells.append(tok(s) + (rf" {{\tiny\textit{{({g})}}}}" if g else ""))
    rows.append(cells)

# Equal column widths: measure every token cell in the table's own font size and set all six
# columns to the widest, capped so the table is no wider than the text. Cells never wrap: one just
# over the cap overhangs into the gap beside it (about 1pt for the current tokens).
L = [r"% Generated by paper-artifacts/jlens_pole_table/jlens_pole_table.py -- do not edit by hand.",
     r"\setlength{\tabcolsep}{2pt}\renewcommand{\arraystretch}{1.05}\scriptsize",
     r"\newlength{\jlcol}\newlength{\jlcell}\setlength{\jlcol}{0pt}"]
for c in [b[0] for b in BLOCKS] + [c for cells in rows for c in cells]:
    L.append(rf"\settowidth{{\jlcell}}{{{c}}}\ifdim\jlcell>\jlcol\setlength{{\jlcol}}{{\jlcell}}\fi")
GAP = "6pt"   # extra space between the rank column and the first pole
L += [r"\settowidth{\jlcell}{%d}\addtolength{\jlcell}{%d\tabcolsep}\addtolength{\jlcell}{%s}"
      % (K, 2 * len(BLOCKS), GAP),
      r"\setlength{\jlcell}{\dimexpr(\linewidth-\jlcell)/%d\relax}" % len(BLOCKS),
      r"\ifdim\jlcol>\jlcell\setlength{\jlcol}{\jlcell}\fi"]
L += [r"\begin{tabular}{@{}l<{\hspace{%s}}*{%d}{>{\raggedright\arraybackslash}p{\jlcol}}@{}}" % (GAP, len(BLOCKS)),
      r"\toprule",
      " & ".join([""] + [b[0] for b in BLOCKS]) + r" \\", r"\midrule"]
L += [" & ".join([str(r_i + 1)] + [rf"\mbox{{{c}}}" for c in cells]) + r" \\" for r_i, cells in enumerate(rows)]
L += [r"\bottomrule", r"\end{tabular}"]
OUT.write_text("\n".join(L) + "\n")
print(OUT)
